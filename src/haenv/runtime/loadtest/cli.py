"""`haenv loadtest` -- rehearse a paid run offline against a fake provider.

    haenv loadtest profile --batches DIR... [--service-batches DIR...] [--generation-samples F]
                           --out PROFILE.yaml --library LIBRARY.jsonl
        Measure a provider profile and a replay library from finished batches.
    haenv loadtest serve   --profile P --library L [--time-scale X] [--port N] --log F
        Run the fake provider in the foreground (point `transport.rehearsal_url` at it).
    haenv loadtest run     SPEC.yaml [--scale N] [--time-scale X] [--kill-at F] [--out DIR]
        Run a rehearsal spec end to end and write the speed report.
    haenv loadtest report  RUN_DIR
        Re-read a finished rehearsal and print its speed report.

See docs/design/loadtest.md.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path


def _read_library(path: Path) -> list[dict]:
    with Path(path).open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def _profile(a) -> int:
    from haenv.runtime.loadtest.profile import build
    like = {}
    for item in a.service_like or []:
        wire, rest = item.split("=", 1)
        other, _, factor = rest.partition("*")
        like[wire] = (other, float(factor or 1))
    limits = {k: int(v) for k, v in (x.split("=", 1) for x in a.max_concurrency or [])}
    profile, library = build([Path(p) for p in a.batches],
                             service_batches=[Path(p) for p in a.service_batches or []],
                             generation_samples=a.generation_samples, service_like=like,
                             max_concurrency=limits)
    rebuild = " ".join(sys.argv[1:]) if sys.argv[1:2] == ["loadtest"] else "haenv loadtest profile ..."
    profile.dump(a.out, header=f"# Generated by `haenv loadtest profile`; do not edit by hand.\n"
                               f"# Rebuild: haenv {rebuild}\n")
    with Path(a.library).open("w", encoding="utf-8") as f:
        for entry in library:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    print(f"profile {a.out}: {len(profile.models)} models, {len(profile.catalog)} catalog entries; "
          f"library {a.library}: {len(library)} answers")
    return 0


def _serve(a) -> int:
    from haenv.runtime.loadtest.profile import Profile
    from haenv.runtime.loadtest.responder import Responder
    from haenv.runtime.loadtest.server import FakeProvider
    fake = FakeProvider(Profile.load(a.profile), Responder(_read_library(a.library), seed=a.seed),
                        a.log, time_scale=a.time_scale, seed=a.seed, port=a.port).start()
    print(f"fake provider at {fake.url} (time scale {a.time_scale}); log {a.log}", flush=True)
    try:
        while True:
            time.sleep(3600)
    except KeyboardInterrupt:
        fake.stop()
    return 0


def _run(a) -> int:
    from haenv.runtime.loadtest.rehearsal import Rehearsal
    report = Rehearsal.from_spec(a.spec, out=a.out, scale=a.scale, time_scale=a.time_scale,
                                 kill_at=a.kill_at).run()
    print(report.text())
    return 0 if report.passed else 1


def _report(a) -> int:
    from haenv.runtime.loadtest.report import SpeedReport
    report = SpeedReport.read(Path(a.run_dir))
    print(report.text())
    return 0 if report.passed else 1


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="haenv loadtest", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("profile", help="measure a provider profile and replay library")
    p.add_argument("--batches", nargs="+", required=True,
                   help="batch directories: answers, prices, error rates, judge service times")
    p.add_argument("--service-batches", nargs="*",
                   help="batch directories run with no wait for a paid slot: solver service times")
    p.add_argument("--generation-samples", type=Path,
                   help="OpenRouter generation records {model: [{generation_time, pack}]}")
    p.add_argument("--service-like", nargs="*", metavar="WIRE=OTHER*FACTOR",
                   help="give a model with no samples another model's service times times a factor")
    p.add_argument("--max-concurrency", nargs="*", metavar="BACKEND=N",
                   help="requests in flight per backend beyond which the fake answers 429")
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--library", type=Path, required=True)
    p.set_defaults(fn=_profile)
    s = sub.add_parser("serve", help="run the fake provider in the foreground")
    s.add_argument("--profile", type=Path, required=True)
    s.add_argument("--library", type=Path, required=True)
    s.add_argument("--time-scale", type=float, default=1.0,
                   help="multiply every service time by this (0.05 = twenty times faster)")
    s.add_argument("--port", type=int, default=0)
    s.add_argument("--seed", type=int, default=0)
    s.add_argument("--log", type=Path, required=True, help="request log (JSONL)")
    s.set_defaults(fn=_serve)
    r = sub.add_parser("run", help="run a rehearsal spec and write the speed report")
    r.add_argument("spec", type=Path)
    r.add_argument("--scale", type=int, default=None, help="multiply the spec's repeats (k)")
    r.add_argument("--time-scale", type=float, default=None)
    r.add_argument("--kill-at", type=float, default=None,
                   help="kill -9 every run process after this fraction of solver answers, then resume")
    r.add_argument("--out", type=Path, default=None)
    r.set_defaults(fn=_run)
    q = sub.add_parser("report", help="print the speed report of a finished rehearsal")
    q.add_argument("run_dir", type=Path)
    q.set_defaults(fn=_report)
    a = ap.parse_args(argv)
    return a.fn(a)
