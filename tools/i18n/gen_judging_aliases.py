"""Generate judging-only English names from the reviewed solver lexicon."""
from __future__ import annotations

import argparse
import difflib
import hashlib
import json
from pathlib import Path
import sys

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / "src"), str(ROOT)]

from haenv.i18n.text import lexicon
from haenv.resources.registry import _load_yaml
from haenv.world import overlay

OUTPUT = ROOT / "registry/judging_aliases_en.yaml"


def universe() -> set[str]:
    """Non-ASCII diagnosis names, excluding findings and independent-only names."""
    names = set()
    for sid, spec in overlay.condition_registry(include_draft=True).items():
        if not spec["diagnosis"].startswith("无统一病理"):
            names.update([spec["diagnosis"], *spec.get("aliases", ())])
        for thread in overlay.threads_for(sid, spec) or ():
            names.update(thread["aliases"])
    threads = _load_yaml("threads.yaml")
    for anchor, row in threads.get("judging_synonyms", {}).items():
        names.add(anchor)
        names.update(row["names"])
    findings = threads.get("finding_aliases", {})
    for row in findings.values():
        names.update(row.get("diagnosis_forms", ()))
    finding_words = {s.lower() for s in findings}
    return {s for s in names if isinstance(s, str) and not s.isascii()
            and s.lower() not in finding_words}


def generate() -> str:
    english = lexicon("en")
    names = {}
    for s in sorted(universe()):
        value = english.get(s)
        if value and (value := value.strip().lower()) and value.isascii():
            names[s] = value
    sha = hashlib.sha256(json.dumps(sorted(english.items()), ensure_ascii=False).encode()).hexdigest()[:16]
    canary = "\n".join((ROOT / "registry/threads.yaml").read_text(encoding="utf-8").splitlines()[:2])
    header = """
# Generated by tools/i18n/gen_judging_aliases.py from the reviewed English lexicon
# (registry/i18n/en/lexicon). Do not edit by hand: run `--write` after a lexicon or registry change;
# `--check` (and its test) fails on drift. Judging side only: `tracks.judging_names` adds
# names[<Chinese gold name>] next to that name. Leak scanning and generation never read this file.
"""
    return canary + header + yaml.safe_dump({
        "source": "registry/i18n/en/lexicon",
        "generator": "tools/i18n/gen_judging_aliases.py",
        "lexicon_sha16": sha,
        "names": names,
    }, allow_unicode=True, sort_keys=False, width=120)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    fresh = generate()
    if args.write:
        OUTPUT.write_text(fresh, encoding="utf-8")
        return 0
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if current != fresh:
        print("judging_aliases_en.yaml differs from fresh generation:")
        print("".join(difflib.unified_diff(current.splitlines(True), fresh.splitlines(True),
                                         fromfile=OUTPUT.name, tofile="fresh generation")), end="")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
